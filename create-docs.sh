# 리스크 점수 계산 사양 (특허 공식)

## 공식
```
R = Fp × Wf + Oc × Wo + Ch × Wc
```

## 변수 정의
| 변수 | 의미 | 범위 | 가중치 기본값 |
|------|------|------|-------------|
| Fp | 재정 리스크 (Financial Probability) | 0~100 | Wf = 0.4 |
| Oc | 발생 빈도 (Occurrence Count) | 0~100 | Wo = 0.35 |
| Ch | 변경 영향 (Change Impact) | 0~100 | Wc = 0.25 |

## 4단계 판정
| 점수 | 등급 | 색상 | 아이콘 | 조치 |
|------|------|------|--------|------|
| 0~25 | 안전 | #10B981 | ✅ | 정상 관리 |
| 26~50 | 주의 | #F59E0B | ⚠️ | 모니터링 강화 |
| 51~75 | 경고 | #F97316 | 🔶 | 즉시 조치 필요 |
| 76~100 | 위험 | #EF4444 | 🔴 | 긴급 대응 |

## 비용 조정 공식
```
ΔC = Cb × (1 + Σ(Wi × Fi))
```
- Cb: 기본 비용
- Wi: 항목별 가중치
- Fi: 조정 요인 (0~1)

## AI 검증 점수
```
총점 = 비용(25) + 공정(25) + 계약(25) + 일정(25) = 100점
```
- 90점 이상: 우수 (인증서 발급)
- 70~89점: 양호
- 50~69점: 보통
- 50점 미만: 미흡

## 업종별 가중치
각 업종(카페, 음식점, 병원 등)별로 Wf, Wo, Wc 가중치가 다르게 설정됩니다.
`src/data/industries/index.ts` 참조.
